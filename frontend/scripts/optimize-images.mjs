import { createHash } from 'node:crypto'
import { mkdir, readdir, readFile, writeFile } from 'node:fs/promises'
import { basename, dirname, relative, resolve } from 'node:path'
import sharp from 'sharp'

const root = resolve(import.meta.dirname, '..')
const assets = resolve(root, 'public/assets')
const output = resolve(assets, 'optimized')
await mkdir(output, { recursive: true })
const manifest = {}
const evidence = []
for (const entry of await readdir(assets, { recursive: true, withFileTypes: true })) {
  if (!entry.isFile() || !entry.name.endsWith('.png')) continue
  const input = resolve(entry.parentPath, entry.name)
  const source = await readFile(input)
  const metadata = await sharp(source).metadata()
  const widths = [...new Set([480, 800, 960, 1280, metadata.width].filter(width => width <= metadata.width))].sort((a, b) => a - b)
  const variants = []
  for (const width of widths) {
    const encoded = await sharp(source).resize({ width, withoutEnlargement: true })
      .webp({ lossless: true, effort: 6 }).toBuffer()
    const hash = createHash('sha256').update(encoded).digest('hex').slice(0, 10)
    const filename = `${basename(input, '.png')}-${width}-${hash}.webp`
    await writeFile(resolve(output, filename), encoded)
    variants.push([width, hash])
    if (width === metadata.width) {
      const original = await sharp(source).ensureAlpha().raw().toBuffer()
      const decoded = await sharp(encoded).ensureAlpha().raw().toBuffer()
      let changedVisiblePixels = 0
      for (let pixel = 0; pixel < original.length; pixel += 4) {
        if (original[pixel + 3] !== decoded[pixel + 3] ||
          (original[pixel + 3] > 0 && !original.subarray(pixel, pixel + 3).equals(decoded.subarray(pixel, pixel + 3)))) changedVisiblePixels++
      }
      if (changedVisiblePixels) throw new Error(`Visible pixels changed: ${input} (${changedVisiblePixels})`)
      evidence.push({ source: `/assets/${relative(assets, input).replaceAll('\\', '/')}`,
        pngBytes: source.length, webpBytes: encoded.length, width: metadata.width, height: metadata.height, changedVisiblePixels })
    }
  }
  manifest[`/assets/${relative(assets, input).replaceAll('\\', '/')}`] = {
    width: metadata.width, height: metadata.height, variants,
  }
}
const manifestPath = resolve(root, 'src/generated/responsiveImages.js')
await mkdir(dirname(manifestPath), { recursive: true })
await writeFile(manifestPath, `// Generated by npm run images:optimize. Keep the original PNG fallback.\nexport const responsiveImages = ${JSON.stringify(manifest, null, 2)}\n`)
await mkdir(resolve(root, 'test-results'), { recursive: true })
await writeFile(resolve(root, 'test-results/image-integrity.json'), JSON.stringify(evidence, null, 2))
console.log(JSON.stringify({ images: evidence.length, originalBytes: evidence.reduce((sum, e) => sum + e.pngBytes, 0),
  losslessWebpBytes: evidence.reduce((sum, e) => sum + e.webpBytes, 0), visiblePixelDifferences: 0 }))
